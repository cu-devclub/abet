#!/usr/bin/env python3
"""
Build every course binder in one go.

Iterates through all `Course-main-tex` directories, runs `latexmk -pdf` for
each `*-main.tex`, and relies on the per-course `latexmkrc` to route build
artifacts into `build/` and `Compiled pdf/`.
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path
from typing import Iterable, Optional


def write_expected_counts(expected_json: Path, output_tex: Path) -> None:
    """Regenerate the LaTeX expected-counts file from the JSON config."""
    data = json.loads(expected_json.read_text())
    lines = [
        "% Auto-generated from expected_counts.json; do not edit manually.",
        "% Generated by scripts/build_all_pdfs.py.",
    ]
    for section, course_map in sorted(data.items()):
        for repo_path, count in sorted(course_map.items()):
            try:
                _, tail = repo_path.split("/", 1)
            except ValueError:
                tail = repo_path
            lines.append(
                f"\\AddExpectedCount{{{section}}}"
                f"{{course_documents/{tail}}}"
                f"{{{count}}}"
            )
    output_tex.write_text("\n".join(lines) + "\n")


def run_latexmk(tex_file: Path, course_dir: Path, *, silent: bool) -> int:
    """Run latexmk for a single course."""
    build_dir = course_dir / "build"
    if build_dir.is_dir():
        fdb = build_dir / f"{tex_file.stem}.fdb_latexmk"
        if fdb.exists():
            fdb.unlink()
    cmd = ["latexmk", "-pdf", "-g"]
    if silent:
        cmd.append("-silent")
    cmd.append(tex_file.name)

    proc = subprocess.run(cmd, cwd=course_dir)
    return proc.returncode


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Build all course binders with latexmk."
    )
    parser.add_argument(
        "--silent",
        action="store_true",
        help="Pass -silent to latexmk to reduce console output.",
    )
    parser.add_argument(
        "--semester",
        help="Build only the given semester directory (e.g. ABET-Course-Display-sem1y1).",
    )
    parser.add_argument(
        "--course",
        help="Build only the given course tex file (basename or relative path).",
    )
    parser.add_argument(
        "--skip-compress",
        action="store_true",
        help="Skip the post-build compression step.",
    )
    args = parser.parse_args(argv)

    root = Path(__file__).resolve().parents[1]

    expected_json = root / "config" / "generated" / "expected_counts.json"
    expected_tex = root / "config" / "generated" / "expected_counts.tex"
    if expected_json.exists():
        print("Regenerating config/generated/expected_counts.tex from JSON …")
        write_expected_counts(expected_json, expected_tex)
    else:
        print("Warning: config/generated/expected_counts.json not found; skipping regeneration.", file=sys.stderr)

    if args.course and args.semester:
        print("Specify either --course or --semester (or neither).", file=sys.stderr)
        return 1

    build_targets = []
    if args.course:
        course_path = Path(args.course)
        if course_path.suffix == '' or course_path.suffix == '.tex':
            if course_path.is_file():
                build_targets.append((course_path.resolve(), course_path.parent.resolve()))
            else:
                matches = list(root.glob(f"**/{course_path.stem}.tex"))
                if not matches:
                    print(f"Course tex not found for {args.course}", file=sys.stderr)
                    return 1
                build_targets.extend((m, m.parent) for m in matches)
        else:
            print("--course must be a .tex file or basename.", file=sys.stderr)
            return 1
    else:
        if args.semester:
            course_tex_dirs = [root / args.semester / 'Course-main-tex']
        else:
            course_tex_dirs = sorted(root.glob("ABET-Course-Display-sem*y*/Course-main-tex"))
        if not course_tex_dirs:
            print("No Course-main-tex directories found.", file=sys.stderr)
            return 1
        for course_dir in course_tex_dirs:
            tex_files = sorted(course_dir.glob("*-main.tex"))
            build_targets.extend((tex_file, course_dir) for tex_file in tex_files)

    if not build_targets:
        print("No course tex files found to build.", file=sys.stderr)
        return 1

    failures: list[Path] = []
    successful_pdfs: list[Path] = []
    for tex_file, course_dir in build_targets:
        rel_path = tex_file.relative_to(root)
        print(f"=== Building {rel_path} ===")
        code = run_latexmk(tex_file, course_dir, silent=args.silent)
        if code != 0:
            failures.append(rel_path)
            print(f"*** FAILED: {rel_path} (exit {code})", file=sys.stderr)
        else:
            print(f"--- OK: {rel_path}")
            compiled_pdf = course_dir / "Compiled pdf" / f"{tex_file.stem}.pdf"
            if compiled_pdf.exists():
                successful_pdfs.append(compiled_pdf)
            else:
                print(
                    f"Warning: expected PDF not found at {compiled_pdf}",
                    file=sys.stderr,
                )

    if failures:
        print("\nThe following builds failed:", file=sys.stderr)
        for rel_path in failures:
            print(f"  - {rel_path}", file=sys.stderr)
        return 1

    print("\nAll course PDFs built successfully.")

    # Nothing more to do if no PDFs were produced (e.g. latexmk skipped output).
    if not successful_pdfs:
        print("No PDFs found to copy; skipping copy/compress steps.")
        return 0

    dest_root = root / "compiled pdf" / "Final compile"
    dest_root.mkdir(parents=True, exist_ok=True)

    compiled_pdfs: list[Path] = []
    seen: set[Path] = set()
    for pdf in successful_pdfs:
        resolved = pdf.resolve()
        if resolved in seen:
            continue
        seen.add(resolved)
        target = dest_root / pdf.name
        shutil.copy2(pdf, target)
        compiled_pdfs.append(target)

    print(f"Copied {len(compiled_pdfs)} PDFs into {dest_root}")

    compressor = root / "scripts" / "compress_pdf.py"
    if args.skip_compress:
        print("Skipping compression step (--skip-compress provided).")
    elif compressor.exists():
        log_path = dest_root / "compression_log.txt"
        xdg_cache = root / ".cache"
        fontconfig_cache = xdg_cache / "fontconfig"
        fontconfig_cache.mkdir(parents=True, exist_ok=True)
        env = os.environ.copy()
        env.setdefault("XDG_CACHE_HOME", str(xdg_cache))

        for pdf in compiled_pdfs:
            compressed = pdf.with_name(f"{pdf.stem}-compressed{pdf.suffix}")
            if compressed.exists():
                compressed.unlink()
            print(f"Compressing {pdf.name} -> {compressed.name}")
            started_at = datetime.now().isoformat(timespec="seconds")
            start_time = time.perf_counter()
            result = subprocess.run(
                [str(compressor), str(pdf), str(compressed)],
                cwd=root,
                env=env,
            )
            elapsed = time.perf_counter() - start_time
            status = "ok" if result.returncode == 0 else f"failed({result.returncode})"
            with log_path.open("a", encoding="utf-8") as log_file:
                log_file.write(
                    f"{started_at}\t{pdf.name}\t{elapsed:.2f}s\t{status}\n"
                )
            if result.returncode != 0:
                print(f"*** Compression failed for {pdf}", file=sys.stderr)
                if compressed.exists():
                    compressed.unlink()
            else:
                compressed.replace(pdf)
    else:
        print("compress_pdf.py not found; skipping compression step.")

    print("All PDFs copied and compressed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
